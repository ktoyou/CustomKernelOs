"""Literal .env settings shared by GNU Make and the Python development tools."""
import argparse,hashlib,os,pathlib,re,sys,tempfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
DEFAULTS={
    'EXT_AUTOINSTALL_PACKAGES':'','EXT_BUILD_JOBS':'auto',
    'SSH_AUTHORIZED_KEY':'','SSH_AUTHORIZED_KEY_FILE':'',
    'CROSS':'i686-elf-' if sys.platform=='darwin' else '',
    'NASM':'nasm','QEMU':'qemu-system-i386','HOSTCC':'cc',
    'DISK':'disk.img','DISK_MB':'4096','DATA_DISK':'',
    'QEMU_MEM':'512M','QEMU_CPUS':'4','QEMU_CPU':'host','QEMU_ACCEL':'kvm','VGA':'auto','GPU':'auto',
    'HOST_PORT':'8080','SSH_PORT':'','USB_VIDEO':'auto','USB_ROOT_MB':'256',
    'NETBOOT_BIND':'0.0.0.0','NETBOOT_PORT':'8080','NETBOOT_URL':'',
    'NETBOOT_DIRECTORY':'build/netboot','NETBOOT_IMAGE':'build/myos-usb.img',
    'NETBOOT_MANIFEST':'build/hardware/manifest.json','IPXE_JOBS':'4',
}
COMPILERS={'CC':'gcc','LD':'ld','AR':'ar','NM':'nm','OBJCOPY':'objcopy'}

def read_env(path):
    if not path.exists():return {}
    result={}
    for number,line in enumerate(path.read_text(encoding='utf-8-sig').splitlines(),1):
        line=line.strip()
        if not line or line.startswith('#'):continue
        if line.startswith('export '):line=line[7:].lstrip()
        match=re.fullmatch(r'([A-Za-z_][A-Za-z_0-9]*)\s*=\s*(.*)',line)
        if not match:raise ValueError(f'{path}:{number}: expected NAME=value')
        key,raw=match.groups()
        if key not in DEFAULTS and key not in COMPILERS:raise ValueError(f'{path}:{number}: unknown setting {key}')
        if raw.startswith(('"',"'")):
            quote=raw[0];end=raw.find(quote,1)
            if end<=0 or (raw[end+1:].strip() and not raw[end+1:].lstrip().startswith('#')):
                raise ValueError(f'{path}:{number}: invalid quoted value for {key}')
            value=raw[1:end]
        else:value=re.split(r'\s+#',raw,maxsplit=1)[0].rstrip()
        if any(c in value for c in ('\x00','\r','\n')):raise ValueError(f'{path}:{number}: control character in {key}')
        result[key]=value
    return result

def settings(path=None,environ=None):
    env=os.environ if environ is None else environ
    file=read_env(ROOT/'.env' if path is None else pathlib.Path(path))
    values=dict(DEFAULTS);values.update(file)
    for key in (*DEFAULTS,*COMPILERS):
        if key in env:values[key]=env[key]
    for key,suffix in COMPILERS.items():values.setdefault(key,values['CROSS']+suffix)
    return values

def project_path(value):
    path=pathlib.Path(value)
    return path if path.is_absolute() else ROOT/path

def make_text(path=None,environ=None):
    env=os.environ if environ is None else environ
    file=read_env(ROOT/'.env' if path is None else pathlib.Path(path))
    values=settings(path,env)
    lines=['# Generated by tools/env_config.py; do not edit.']
    for key,value in values.items():
        # Toolchain defaults must follow a command-line CROSS override in Make.
        if key in COMPILERS and key not in file and key not in env:
            escaped='$(CROSS)'+COMPILERS[key]
        else:
            escaped=re.sub(r'(\\*)#',lambda match:'\\'*(2*len(match[1])+1)+'#',value.replace('$','$$'))
            if value.startswith((' ','\t')):escaped='$(strip )'+escaped
            # A trailing backslash must not continue the next Make assignment.
            if escaped.endswith('\\'):escaped+='$(strip )'
        lines += [f'ifeq ($(origin {key}),default)',f'{key} := {escaped}','endif',f'{key} ?= {escaped}']
    lines.append('export '+' '.join(values))
    return '\n'.join(lines)+'\n'

def make_file():
    data=make_text().encode('utf-8')
    directory=ROOT/'build/config';directory.mkdir(parents=True,exist_ok=True)
    target=directory/('env-'+hashlib.sha256(data).hexdigest()+'.mk')
    if not target.exists():
        fd,name=tempfile.mkstemp(dir=directory)
        try:
            with os.fdopen(fd,'wb') as out:out.write(data)
            os.replace(name,target)
        finally:pathlib.Path(name).unlink(missing_ok=True)
    # Make is invoked from the project root, so no host/WSL absolute path leaks.
    return target.relative_to(ROOT).as_posix()

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--make-file',action='store_true');args=ap.parse_args()
    try:
        if args.make_file:print(make_file())
    except (ValueError,OSError) as error:ap.exit(2,str(error)+'\n')

if __name__=='__main__':main()
